  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO stocksafe_app;
ALTER DEFAULT PRIVILEGES FOR ROLE stocksafe IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO stocksafe_app;
